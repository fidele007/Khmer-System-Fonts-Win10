#!/usr/bin/env python3
"""Replace a font's Khmer subsystem with glyphs from any replacement font.

The output uses the replacement font as the structural base, so its Khmer glyph set,
metrics, glyph order, and GSUB/GPOS shaping data stay together. Simple
non-Khmer outlines and metrics from the input font are copied back where the
glyphs are present in both fonts. The input font's name table is preserved.

Example:
    python tools/replace_khmer_font.py \
        --scale 1.25 \
        --pair input.ttf ReplacementFont.ttf output.ttf

Install the dependency with: python -m pip install fonttools
"""

from __future__ import annotations

import argparse
from copy import deepcopy
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._g_l_y_f import GlyphCoordinates


KHMER_RANGES = ((0x1780, 0x17FF), (0x19E0, 0x19FF))
POSITION_ATTRIBUTES = {
    "XCoordinate",
    "YCoordinate",
    "XPlacement",
    "YPlacement",
    "XAdvance",
    "YAdvance",
    "x",
    "y",
    "xAdvance",
    "yAdvance",
}


def get_cmap(font: TTFont) -> dict[int, str]:
    return {
        codepoint: glyph_name
        for table in font["cmap"].tables
        for codepoint, glyph_name in table.cmap.items()
    }


def is_khmer(codepoint: int) -> bool:
    return any(start <= codepoint <= end for start, end in KHMER_RANGES)


def copy_simple_glyph(
    source_glyph,
    source_glyf,
    source_units_per_em: int,
    target_units_per_em: int,
):
    """Copy a simple TrueType glyph and scale it to the target em size."""
    source_glyph.expand(source_glyf)
    if source_glyph.isComposite():
        # Component names belong to the source font, so leave these glyphs
        # from the replacement font's structural base instead.
        return None

    scale = target_units_per_em / source_units_per_em
    coordinates, end_points, flags = source_glyph.getCoordinates(source_glyf)
    result = deepcopy(source_glyph)
    result.endPtsOfContours = deepcopy(end_points)
    result.flags = deepcopy(flags)
    result.coordinates = GlyphCoordinates(
        [(round(x * scale), round(y * scale)) for x, y in coordinates]
    )
    return result


def copy_non_khmer_outlines(input_font: TTFont, replacement_font: TTFont) -> int:
    """Restore simple non-Khmer outlines from the input font."""
    input_cmap = get_cmap(input_font)
    replacement_cmap = get_cmap(replacement_font)
    copied = 0
    source_units = input_font["head"].unitsPerEm
    target_units = replacement_font["head"].unitsPerEm
    scale = target_units / source_units

    for codepoint, source_name in input_cmap.items():
        if is_khmer(codepoint) or codepoint not in replacement_cmap:
            continue

        target_name = replacement_cmap[codepoint]
        source_glyph = input_font["glyf"].glyphs[source_name]
        result = copy_simple_glyph(
            source_glyph,
            input_font["glyf"],
            source_units,
            target_units,
        )
        if result is None:
            continue

        replacement_font["glyf"].glyphs[target_name] = result
        advance, lsb = input_font["hmtx"][source_name]
        replacement_font["hmtx"][target_name] = (
            round(advance * scale),
            round(lsb * scale),
        )
        copied += 1

    return copied


def khmer_glyph_closure(font: TTFont) -> set[str]:
    """Find Khmer glyphs generated by GSUB, including subscripts."""
    s = subset.Subsetter()
    requested = [
        codepoint
        for start, end in KHMER_RANGES
        for codepoint in range(start, end + 1)
    ]
    s.populate(unicodes=requested)
    s._closure_glyphs(font)
    return set(s.glyphs_retained) - {".notdef", "uni200D"}


def scale_glyph(glyph, glyf_table, factor: float):
    glyph.expand(glyf_table)
    result = deepcopy(glyph)

    if glyph.isComposite():
        for component in result.components:
            component.x = round(component.x * factor)
            component.y = round(component.y * factor)
            component.xx = round(getattr(component, "xx", 1) * factor, 8)
            component.xy = round(getattr(component, "xy", 0) * factor, 8)
            component.yx = round(getattr(component, "yx", 0) * factor, 8)
            component.yy = round(getattr(component, "yy", 1) * factor, 8)
    else:
        coordinates, end_points, flags = glyph.getCoordinates(glyf_table)
        result.endPtsOfContours = deepcopy(end_points)
        result.flags = deepcopy(flags)
        result.coordinates = GlyphCoordinates(
            [(round(x * factor), round(y * factor)) for x, y in coordinates]
        )

    return result


def scale_positioning_object(obj, factor: float) -> None:
    if isinstance(obj, list):
        for item in obj:
            scale_positioning_object(item, factor)
        return
    if not hasattr(obj, "__dict__"):
        return

    for attribute, value in vars(obj).items():
        if attribute in POSITION_ATTRIBUTES and isinstance(value, (int, float)):
            setattr(obj, attribute, round(value * factor))
        elif isinstance(value, list) or hasattr(value, "__dict__"):
            scale_positioning_object(value, factor)


def scale_khmer_positioning(font: TTFont, factor: float) -> None:
    if "GPOS" not in font:
        return

    table = font["GPOS"].table
    lookup_indices: set[int] = set()
    for record in table.FeatureList.FeatureRecord:
        if record.FeatureTag in {"abvm", "blwm", "mark", "mkmk"}:
            lookup_indices.update(record.Feature.LookupListIndex)

    for index in lookup_indices:
        for subtable in table.LookupList.Lookup[index].SubTable:
            scale_positioning_object(subtable, factor)


def enlarge_khmer(font: TTFont, factor: float) -> int:
    if factor == 1.0:
        return 0

    names = khmer_glyph_closure(font)
    for name in names:
        if name not in font["glyf"].glyphs:
            continue
        font["glyf"].glyphs[name] = scale_glyph(
            font["glyf"].glyphs[name], font["glyf"], factor
        )
        advance, lsb = font["hmtx"][name]
        font["hmtx"][name] = (
            round(advance * factor),
            round(lsb * factor),
        )

    scale_khmer_positioning(font, factor)
    return len(names)


def process_pair(input_path: Path, replacement_path: Path, output_path: Path, factor: float):
    input_font = TTFont(str(input_path))
    replacement_font = TTFont(str(replacement_path))

    copied = copy_non_khmer_outlines(input_font, replacement_font)
    enlarged = enlarge_khmer(replacement_font, factor)

    # Keep all original name records, including localized names.
    replacement_font["name"] = deepcopy(input_font["name"])
    output_path.parent.mkdir(parents=True, exist_ok=True)
    replacement_font.save(str(output_path))

    khmer_count = len({
        codepoint
        for codepoint in get_cmap(replacement_font)
        if is_khmer(codepoint)
    })
    print(
        f"{output_path}: Khmer={khmer_count}, "
        f"enlarged={enlarged}, non-Khmer outlines copied={copied}, "
        f"scale={factor:g}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--scale",
        type=float,
        default=1.0,
        help="Khmer enlargement factor; 1.0 keeps replacement-font size (default: 1.0)",
    )
    parser.add_argument(
        "--pair",
        nargs=3,
        action="append",
        metavar=("INPUT_FONT", "REPLACEMENT_FONT", "OUTPUT_FONT"),
        required=True,
        help="Input, replacement font, and output font; repeatable",
    )
    args = parser.parse_args()

    if args.scale <= 0:
        parser.error("--scale must be greater than zero")

    for input_name, replacement_name, output_name in args.pair:
        process_pair(
            Path(input_name),
            Path(replacement_name),
            Path(output_name),
            args.scale,
        )


if __name__ == "__main__":
    main()
